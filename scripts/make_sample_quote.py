"""Draws web/sample-quote.png: a fictional vendor's quotation with the traps households run into.

    python scripts/make_sample_quote.py
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

OUT = Path(__file__).resolve().parents[1] / "web" / "sample-quote.png"


def font(name: str, size: int):
    try:
        return ImageFont.truetype(name, size)
    except OSError:
        return ImageFont.load_default()


regular, bold, big, small = font("arial.ttf", 22), font("arialbd.ttf", 22), font("arialbd.ttf", 30), font("arial.ttf", 18)
img = Image.new("RGB", (1000, 1300), "white")
d = ImageDraw.Draw(img)

d.rectangle([0, 0, 1000, 60], fill="#b91c1c")
d.text((24, 16), "SAMPLE QUOTATION FOR DEMONSTRATION - FICTIONAL VENDOR, NOT A REAL OFFER", fill="white", font=bold)
d.text((40, 90), "Sunrise Rooftop Energy (sample)", fill="#0f172a", font=big)
d.text((40, 132), "Quotation No. SQ-0001        Date: 05-10-2026        Valid for 15 days", fill="#334155", font=regular)
d.text((40, 180), "Subject: 3 kW On-Grid Rooftop Solar System under PM Surya Ghar", fill="#0f172a", font=bold)

rows = [
    ("1", "Solar modules: Brightcell 545 Wp Mono PERC, non-DCR (imported cells)", "5 nos"),
    ("2", "On-grid inverter: Voltex 2 kW, single phase", "1 no"),
    ("3", "Module mounting structure, GI, elevated", "1 set"),
    ("4", "DC and AC cables, MC4 connectors", "1 lot"),
    ("5", "Installation and commissioning", "1 job"),
]
y = 240
d.rectangle([40, y, 960, y + 40], fill="#e2e8f0")
for x, label in ((50, "S.No"), (130, "Description"), (850, "Qty")):
    d.text((x, y + 9), label, fill="#0f172a", font=bold)
y += 40
for n, desc, qty in rows:
    d.line([40, y, 960, y], fill="#cbd5e1")
    d.text((60, y + 12), n, fill="#0f172a", font=regular)
    d.text((130, y + 12), desc, fill="#0f172a", font=regular)
    d.text((850, y + 12), qty, fill="#0f172a", font=regular)
    y += 50
d.line([40, y, 960, y], fill="#cbd5e1")

y += 30
for label, value in (
    ("Total system cost", "Rs 2,25,000 + GST extra"),
    ("PM Surya Ghar subsidy (we handle everything)", "Rs 94,800"),
    ("Your effective cost", "Rs 1,30,200 + GST"),
):
    d.text((60, y), label, fill="#0f172a", font=regular)
    d.text((640, y), value, fill="#0f172a", font=bold)
    y += 40

y += 20
d.text((40, y), "Warranty", fill="#0f172a", font=bold)
y += 36
for line in ("Module performance warranty: 10 years", "Inverter warranty: 2 years", "System workmanship warranty: 1 year"):
    d.text((60, y), "- " + line, fill="#0f172a", font=regular)
    y += 34

y += 20
d.text((40, y), "Terms", fill="#0f172a", font=bold)
y += 36
for line in ("Payment: 70% advance with order, 30% after installation", "Net metering charges extra, as per DISCOM", "Installation within 30 days of advance"):
    d.text((60, y), "- " + line, fill="#0f172a", font=regular)
    y += 34

d.text((40, 1250), "Generated by Surya Saathi to show what its quote checker catches. Brands and vendor are made up.", fill="#64748b", font=small)
img.save(OUT)
print(OUT)
